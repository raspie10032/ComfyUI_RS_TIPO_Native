import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../web/download-status.js', import.meta.url), 'utf8');
const {formatDownloadStatus, bindDownloadStatus} = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const data = {node:'7', phase:'downloading', filename:'model.safetensors', current:1048576, total:2097152};
assert.equal(formatDownloadStatus(data), 'Downloading model.safetensors · 50.0% · 1.0 / 2.0 MiB');
assert.match(formatDownloadStatus({...data,phase:'verifying'}), /Checking SHA-256/);
assert.match(formatDownloadStatus({...data,phase:'ready'}), /verified/);
assert.match(formatDownloadStatus({...data,phase:'stopped'}), /resume/);
const listeners = {}, node = {}, panel = {}, panels = new WeakMap([[node,panel]]);
bindDownloadStatus({addEventListener(name, fn){listeners[name]=fn;}}, {graph:{getNodeById(id){return id==='7'?node:null;}}}, panels);
listeners.rs_tipo_download({detail:data});
assert.match(panel.textContent,/50.0%/);
listeners.rs_tipo_download({detail:{...data,node:'8'}});
assert.match(panel.textContent,/50.0%/,'unrelated node cannot overwrite status');
listeners.executed({detail:{node:'7'}});
assert.match(panel.textContent,/complete/);
assert.doesNotThrow(()=>listeners.rs_tipo_download({detail:null}));
console.log('Download status formatting, node routing and completion PASS');
